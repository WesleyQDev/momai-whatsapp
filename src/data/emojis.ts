export function isFlagEmoji(emoji: string): boolean {
  for (const char of emoji) {
    const cp = char.codePointAt(0)
    if (cp && cp >= 0x1f1e6 && cp <= 0x1f1ff) {
      return true
    }
  }
  return (
    emoji.includes('🏁') ||
    emoji.includes('🚩') ||
    emoji.includes('🎌') ||
    emoji.includes('🏴') ||
    emoji.includes('🏳️')
  )
}

export function getEmojiTwemojiUrl(emoji: string): string {
  const cleanCodePoints = [...emoji]
    .map((c) => c.codePointAt(0)?.toString(16))
    .filter((c) => c && c !== 'fe0f')
    .join('-')
  return `https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/${cleanCodePoints}.svg`
}

